import 'dart:developer';

import 'package:flutter_local_notifications/flutter_local_notifications.dart';
import 'package:flutter_timezone/flutter_timezone.dart';
import 'package:timezone/data/latest.dart' as tz;
import 'package:timezone/timezone.dart' as tz;

import '../domain/smart_notification.dart';

class LocalNotificationService {
  LocalNotificationService._();
  static final LocalNotificationService instance = LocalNotificationService._();
  final FlutterLocalNotificationsPlugin _plugin = FlutterLocalNotificationsPlugin();
  bool _initialized = false;
  bool _timezoneInitialized = false;
  static const _channelId = 'imaanly_smart_notifications';
  static const _channelName = 'Imaanly reminders';
  static const _channelDescription = 'Personal worship reminders generated by Imaanly.';

  Future<void> initialize() async {
    if (_initialized) return;
    const android = AndroidInitializationSettings('@mipmap/ic_launcher');
    const darwin = DarwinInitializationSettings(requestAlertPermission: false, requestBadgePermission: false, requestSoundPermission: false);
    const linux = LinuxInitializationSettings(defaultActionName: 'Open Imaanly');
    await _plugin.initialize(const InitializationSettings(android: android, iOS: darwin, macOS: darwin, linux: linux));
    await _plugin.resolvePlatformSpecificImplementation<AndroidFlutterLocalNotificationsPlugin>()?.createNotificationChannel(const AndroidNotificationChannel(_channelId, _channelName, description: _channelDescription, importance: Importance.high));
    await _initializeDeviceTimezone();
    _initialized = true;
  }

  Future<bool> requestPermissions() async {
    await initialize();
    final android = _plugin.resolvePlatformSpecificImplementation<AndroidFlutterLocalNotificationsPlugin>();
    final androidGranted = await android?.requestNotificationsPermission();
    final iosGranted = await _plugin.resolvePlatformSpecificImplementation<IOSFlutterLocalNotificationsPlugin>()?.requestPermissions(alert: true, badge: true, sound: true);
    final macGranted = await _plugin.resolvePlatformSpecificImplementation<MacOSFlutterLocalNotificationsPlugin>()?.requestPermissions(alert: true, badge: true, sound: true);
    return androidGranted ?? iosGranted ?? macGranted ?? true;
  }

  /// Requests Android's user-controlled "Alarms & reminders" access.
  /// Returns true when exact alarms are available, and true on non-Android
  /// platforms where this permission does not apply.
  Future<bool> requestExactAlarmPermission() async {
    await initialize();
    final android = _plugin.resolvePlatformSpecificImplementation<AndroidFlutterLocalNotificationsPlugin>();
    if (android == null) return true;
    final alreadyAllowed = await android.canScheduleExactNotifications();
    if (alreadyAllowed == true) return true;
    return await android.requestExactAlarmsPermission() ?? false;
  }

  Future<bool> canScheduleExactAlarms() async {
    await initialize();
    final android = _plugin.resolvePlatformSpecificImplementation<AndroidFlutterLocalNotificationsPlugin>();
    if (android == null) return true;
    return await android.canScheduleExactNotifications() ?? false;
  }

  Future<void> deliver(SmartNotificationCandidate candidate) async {
    await initialize();
    await _plugin.show(_notificationId(candidate), candidate.title, candidate.body, _details(), payload: candidate.reason);
  }

  Future<void> schedulePrayerReminder({required String prayerName, required DateTime prayerAt, int reminderMinutes = 10, bool silent = false}) async {
    await initialize();
    final scheduledAt = prayerAt.subtract(Duration(minutes: reminderMinutes));
    if (!scheduledAt.isAfter(DateTime.now())) return;
    final details = NotificationDetails(
      android: AndroidNotificationDetails(_channelId, _channelName, channelDescription: _channelDescription, importance: silent ? Importance.low : Importance.high, priority: silent ? Priority.low : Priority.high, playSound: !silent, category: AndroidNotificationCategory.alarm),
      iOS: DarwinNotificationDetails(presentSound: !silent),
      macOS: DarwinNotificationDetails(presentSound: !silent),
      linux: const LinuxNotificationDetails(urgency: LinuxNotificationUrgency.normal),
    );
    await _schedule(zonedDate: tz.TZDateTime.from(scheduledAt, tz.local), id: _prayerNotificationId(prayerName, prayerAt), title: '$prayerName is approaching', body: reminderMinutes <= 0 ? 'It is time for $prayerName.' : '$prayerName begins in $reminderMinutes minutes.', details: details, payload: 'prayer:${prayerName.toLowerCase()}');
  }

  Future<void> scheduleGenericReminder({required String title, required String body, required DateTime scheduledAt}) async {
    await initialize();
    if (!scheduledAt.isAfter(DateTime.now())) return;
    final id = _stableHash('generic:$title:${scheduledAt.toIso8601String()}');
    await _schedule(zonedDate: tz.TZDateTime.from(scheduledAt, tz.local), id: id, title: title, body: body, details: _details(), payload: 'generic_reminder');
  }

  /// Schedule a reminder at the same local clock time every day.
  Future<void> scheduleDailyReminder({required int id, required String title, required String body, required DateTime time}) async {
    await initialize();
    final now = tz.TZDateTime.now(tz.local);
    var next = tz.TZDateTime(tz.local, now.year, now.month, now.day, time.hour, time.minute);
    if (!next.isAfter(now)) next = next.add(const Duration(days: 1));
    final exact = await canScheduleExactAlarms();
    await _plugin.zonedSchedule(id, title, body, next, _details(), androidScheduleMode: exact ? AndroidScheduleMode.exactAllowWhileIdle : AndroidScheduleMode.inexactAllowWhileIdle, matchDateTimeComponents: DateTimeComponents.time, payload: 'dhikr_daily_reminder');
  }

  Future<void> _schedule({required tz.TZDateTime zonedDate, required int id, required String title, required String body, required NotificationDetails details, required String payload}) async {
    final exact = await canScheduleExactAlarms();
    await _plugin.zonedSchedule(id, title, body, zonedDate, details, androidScheduleMode: exact ? AndroidScheduleMode.exactAllowWhileIdle : AndroidScheduleMode.inexactAllowWhileIdle, payload: payload);
  }

  Future<void> cancel(int id) async {
    await initialize();
    await _plugin.cancel(id);
  }

  Future<void> cancelPrayerReminder({required String prayerName, required DateTime prayerAt}) async {
    await initialize();
    await _plugin.cancel(_prayerNotificationId(prayerName, prayerAt));
  }

  Future<void> cancelAll() async { await initialize(); await _plugin.cancelAll(); }

  Future<void> _initializeDeviceTimezone() async {
    if (_timezoneInitialized) return;
    tz.initializeTimeZones();
    _timezoneInitialized = true;
    try {
      final timezoneName = await FlutterTimezone.getLocalTimezone();
      tz.setLocalLocation(tz.getLocation(timezoneName));
    } catch (error, stackTrace) {
      log('Could not resolve device timezone; using timezone package default: $error', name: 'LocalNotificationService', stackTrace: stackTrace);
    }
  }

  NotificationDetails _details() => const NotificationDetails(android: AndroidNotificationDetails(_channelId, _channelName, channelDescription: _channelDescription, importance: Importance.high, priority: Priority.high, category: AndroidNotificationCategory.reminder), iOS: DarwinNotificationDetails(), macOS: DarwinNotificationDetails(), linux: LinuxNotificationDetails(urgency: LinuxNotificationUrgency.normal));
  int _notificationId(SmartNotificationCandidate c) => _stableHash('${c.category.name}:${c.reason}:${c.title}');
  int _prayerNotificationId(String name, DateTime at) => _stableHash('prayer:${at.year}-${at.month}-${at.day}:${name.toLowerCase()}');
  int _stableHash(String value) { var hash = 0; for (final unit in value.codeUnits) { hash = 0x1fffffff & (hash + unit); hash = 0x1fffffff & (hash + ((hash & 0x0007ffff) << 10)); hash ^= hash >> 6; } return hash & 0x7fffffff; }
  void logError(Object error, StackTrace stackTrace) => log('Local notification error: $error', name: 'LocalNotificationService', stackTrace: stackTrace);
}
